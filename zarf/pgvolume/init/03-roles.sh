#!/bin/bash

set -e
PREFIX="poc"

psql -v ON_ERROR_STOP=1 --username="$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE ROLE "${PREFIX}_dev" LOGIN PASSWORD '$DEV_PASSWORD';
    CREATE ROLE "${PREFIX}_user" LOGIN PASSWORD '$USER_PASSWORD';

    GRANT CONNECT ON DATABASE $POSTGRES_DB TO "${PREFIX}_dev", "${PREFIX}_user";

    GRANT USAGE, CREATE ON SCHEMA public TO "${PREFIX}_dev";
    GRANT USAGE ON SCHEMA public TO "${PREFIX}_user";
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE smoke TO "${PREFIX}_user";
    GRANT USAGE, SELECT ON SEQUENCE smoke_id_seq TO "${PREFIX}_user";

    ALTER DEFAULT PRIVILEGES FOR ROLE "${PREFIX}_dev" IN SCHEMA public
        GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "${PREFIX}_user";

    ALTER DEFAULT PRIVILEGES FOR ROLE "${PREFIX}_dev" IN SCHEMA public
        GRANT USAGE, SELECT ON SEQUENCES TO "${PREFIX}_user";
EOSQL
